                full = 'function ' + cls + '.' + mn + '(' + '; '.join(sign + ['const Options: TRaimsRequestOptions']) + '): ' + rt + ';\nvar\n' + vars + 'begin\n'
                if required:
                    full += "  if Params = nil then raise EArgumentNilException.Create('Params');\n"
