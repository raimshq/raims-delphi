#!/usr/bin/env python3
"""Generate the Delphi public SDK deterministically from its pinned contract."""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parent.parent
MARKER = '// Generated by scripts/generate.py. Do not edit.\n'
VERBS = {'get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'trace'}
RESERVED = set('and array as asm begin case class const constructor destructor dispinterface div do downto else end except exports file final finalization finally for function goto if implementation in inherited initialization inline interface is label library mod nil not object of on operator or out packed private procedure program property protected public published raise record repeat resourcestring set shl shr string then threadvar to try type unit until uses var while with xor'.split())
OBJECT_MEMBERS = set('Create Destroy Free FreeInstance NewInstance AfterConstruction BeforeDestruction ClassName ClassType ClassInfo ClassParent ClassNameIs InstanceSize CleanupInstance DefaultHandler Dispatch Equals GetHashCode SafeCallException MethodAddress MethodName FieldAddress GetInterface GetInterfaceEntry GetInterfaceTable InheritsFrom QualifiedClassName UnitName UnitScope DisposeOf CheckDisposed GetDisposed ToString'.split())
# FieldError.Field intentionally hides the protected Field helper; generated getters use GetString instead.
JSON_MEMBERS = OBJECT_MEMBERS | set('FData SetValue HasField IsNull GetString GetInt64 GetDouble GetBoolean GetObject GetArray RawJson ToJson ToString'.split())
RESOURCE_MEMBERS = JSON_MEMBERS | {'FLastResponse', 'LastResponse'}
PARAMS_MEMBERS = JSON_MEMBERS | set('SetString SetInt64 SetBoolean SetJson SetNull Unset'.split())
COLLECTION_MEMBERS = RESOURCE_MEMBERS | set('FLoader FInitialAfter FInitialBefore Navigate Cursor AttachPageLoader GetPage AutoPagingEach'.split())
IMPORTED_TYPES = set('TObject TJSONObject TJSONArray TJSONValue TJSONString TJSONNumber TJSONBool TJSONNull TJSONPair TArray TRaimsHeader TRaimsResponseMetadata TRaimsResponse TRaimsRequestAttempt TRaimsRequestObserver TRaimsRequestOptions TRaimsClientOptions TRaimsHttpRequest TRaimsHttpResponse IRaimsTransport TRaimsObject TRaimsParams TRaimsResource IRaimsRequestor TRaimsService TRaimsCollection TRaimsPageLoader'.split())


def name(value):
    parts = re.findall('[A-Za-z0-9]+', value)
    result = ''.join(p[:1].upper() + p[1:] for p in parts)
    if not result or result[0].isdigit():
        result = 'Value' + result
    return result


def identifier(value):
    result = name(value)
    return '&' + result if result.lower() in RESERVED else result


def literal(value):
    return "'" + str(value).replace("'", "''") + "'"


def typename(key, request=False):
    return 'T' + (key[:-7] + 'Params' if request and key.endswith('Request') else key)


class Generator:
    def __init__(self, root=ROOT):
        self.root = root
        self.outputs = {}
        self.source = json.loads((root / 'contracts/source.json').read_text(encoding='utf-8-sig'))
        raw = (root / 'contracts/openapi.json').read_bytes()
        if hashlib.sha256(raw).hexdigest() != self.source['sha256']:
            raise ValueError('Pinned contract SHA-256 mismatch')
        if not re.fullmatch('[0-9a-f]{40}', self.source['revision']):
            raise ValueError('An immutable public contract revision is required')
        expected = 'https://raw.githubusercontent.com/raimshq/openapi/' + self.source['revision'] + '/latest/openapi.spec3.json'
        if self.source['url'] != expected or self.source['repository'] != 'https://github.com/raimshq/openapi':
            raise ValueError('Contract provenance does not identify the public source')
        self.spec = json.loads(raw)
        if self.spec['info']['version'] != self.source['api_version']:
            raise ValueError('API version differs from provenance')
        self.schemas = dict(self.spec['components']['schemas'])
        schema_names = {}
        for key in self.schemas:
            self.add_symbol(schema_names, key, 'component ' + key, 'schema components')
        self.type_symbols = {}
        for value in IMPORTED_TYPES:
            self.add_symbol(self.type_symbols, value, 'imported type', 'generated types')
        self.services = json.loads((root / 'contracts/service-map.json').read_text(encoding='utf-8-sig'))
        self.operations = {}
        self.input_schemas = set()
        self.validate(self.spec)
        for path, item in self.spec['paths'].items():
            for method, operation in item.items():
                if method not in VERBS:
                    continue
                key = operation['operationId']
                if key in self.operations or operation.get('x-raims-availability', 'production') != 'production':
                    raise ValueError('Duplicate or unpublished operation: ' + key)
                if not any('BearerAuth' in security for security in operation.get('security', self.spec.get('security', []))):
                    raise ValueError('Operation does not support API keys: ' + key)
                params = [self.resolve(p) for p in item.get('parameters', []) + operation.get('parameters', [])]
                identities = [(p['in'], p['name']) for p in params]
                if len(set(identities)) != len(identities):
                    raise ValueError('Duplicate parameters: ' + key)
                paths = {p['name'] for p in params if p['in'] == 'path'}
                if paths != set(re.findall(r'\{([^{}]+)\}', path)):
                    raise ValueError('Path parameters differ: ' + key)
                for p in params:
                    if p['in'] not in {'query', 'path', 'header'} or p['in'] == 'header' and p['name'] not in {'X-Raims-Environment', 'Idempotency-Key'}:
                        raise ValueError('Unsupported parameter location or header: ' + key)
                    if p['in'] == 'query' and self.kind(p['schema']) not in {'string', 'integer', 'boolean'}:
                        raise ValueError('Unsupported query type: ' + key)
                op = dict(operation, method=method.upper(), path=path, parameters=params)
                self.operations[key] = op
                body = self.resolve(op.get('requestBody', {}))
                if body:
                    if set(body.get('content', {})) != {'application/json'}:
                        raise ValueError('Only JSON request bodies are supported: ' + key)
                    schema = body['content']['application/json']['schema']
                    if '$ref' not in schema or self.kind(schema) != 'object':
                        raise ValueError('Operation request must reference an object: ' + key)
                    self.input_schemas.add(self.schema_key(schema['$ref']))
        mapped = [op for methods in self.services.values() for op in methods.values()]
        if len(set(mapped)) != len(mapped) or set(mapped) != set(self.operations) or len(mapped) != self.source['operations']:
            raise ValueError('Service map must cover every published operation exactly once')
        self.check_symbols(self.services, 'services')
        for methods in self.services.values():
            self.check_symbols(methods, 'service methods')
        for key, schema in self.schemas.items():
            if self.kind(schema) != 'object' or not self.normalize(schema).get('properties'):
                raise ValueError('Component type requires an explicit compatibility decision: ' + key)

    @staticmethod
    def check_symbols(values, context):
        symbols = [name(v).lower() for v in values]
        if len(set(symbols)) != len(symbols):
            raise ValueError('Delphi symbol collision in ' + context)

    @staticmethod
    def add_symbol(symbols, value, owner, context):
        value = value.lstrip('&')
        if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]{0,254}', value):
            raise ValueError('Invalid Delphi identifier in ' + context + ': ' + value)
        folded = value.lower()
        if folded in symbols:
            raise ValueError('Delphi symbol collision in ' + context + ': ' + value + ' (' + owner + ' conflicts with ' + symbols[folded] + ')')
        symbols[folded] = owner

    def member_symbols(self, inherited, context):
        symbols = {}
        for value in inherited:
            self.add_symbol(symbols, value, 'inherited member', context)
        return symbols

    def add_type(self, value, owner):
        self.add_symbol(self.type_symbols, value, owner, 'generated types')

    def resolve(self, value, seen=None):
        if seen is None:
            seen = set()
        while '$ref' in value:
            ref = value['$ref']
            if not ref.startswith('#/components/') or ref in seen:
                raise ValueError('External or cyclic reference: ' + ref)
            seen.add(ref)
            resolved = self.spec
            for part in ref[2:].split('/'):
                resolved = resolved[part.replace('~1', '/').replace('~0', '~')]
            value = dict(resolved, **{k: v for k, v in value.items() if k != '$ref'})
        return value

    def validate(self, value):
        if isinstance(value, list):
            for child in value:
                self.validate(child)
        elif isinstance(value, dict):
            if '$ref' in value:
                self.resolve(value)
            if 'allOf' in value or 'oneOf' in value:
                raise ValueError('Unsupported schema composition')
            if 'anyOf' in value and (len(value['anyOf']) != 2 or sum(v.get('type') == 'null' for v in value['anyOf']) != 1):
                raise ValueError('Only nullable anyOf is supported')
            for child in value.values():
                self.validate(child)

    def normalize(self, schema):
        schema = dict(schema)
        seen = set()
        while '$ref' in schema or 'anyOf' in schema:
            if '$ref' in schema:
                schema = self.resolve(schema, seen)
                continue
            variants = schema.pop('anyOf')
            if len(variants) != 2 or sum(v.get('type') == 'null' for v in variants) != 1:
                raise ValueError('Only nullable anyOf is supported')
            child = next(v for v in variants if v.get('type') != 'null')
            schema = dict(child, **schema)
            schema['nullable'] = True
        return schema

    def kind(self, schema):
        kind = self.normalize(schema).get('type')
        if isinstance(kind, list):
            kinds = [v for v in kind if v != 'null']
            if len(kinds) != 1:
                raise ValueError('Unsupported type union')
            return kinds[0]
        return kind

    def nullable(self, schema):
        value = self.normalize(schema)
        return value.get('nullable', False) or value.get('type') == 'null' or isinstance(value.get('type'), list) and 'null' in value['type']

    @staticmethod
    def schema_key(ref):
        prefix = '#/components/schemas/'
        if not ref.startswith(prefix):
            raise ValueError('Expected a local schema reference')
        return ref[len(prefix):].replace('~1', '/').replace('~0', '~')

    def delphi_type(self, schema, request=False):
        kind = self.kind(schema)
        reference = schema
        if 'anyOf' in reference:
            reference = next(v for v in reference['anyOf'] if v.get('type') != 'null')
        if '$ref' in reference and kind == 'object':
            key = self.schema_key(reference['$ref'])
            return typename(key, request and key in self.input_schemas)
        if kind in {'string', 'integer', 'boolean', 'number'}:
            return {'string': 'string', 'integer': 'Int64', 'boolean': 'Boolean', 'number': 'Double'}[kind]
        if kind == 'object':
            return 'TJSONObject'
        if kind == 'array':
            item = self.normalize(schema)['items']
            if self.nullable(item):
                return 'TJSONArray'
            if self.kind(item) not in {'string', 'integer', 'boolean', 'object'}:
                raise ValueError('Unsupported typed array item shape: ' + str(item))
            return 'TArray<' + self.delphi_type(item, request) + '>'
        raise ValueError('Unsupported property type: ' + str(schema))

    def response_schema(self, key, op):
        variants = {}
        for status, raw in op['responses'].items():
            if status.isdigit() and 200 <= int(status) < 300:
                response = self.resolve(raw)
                content = response.get('content', {})
                if content and set(content) != {'application/json'}:
                    raise ValueError('Unsupported response content: ' + key)
                schema = content.get('application/json', {}).get('schema')
                if content and (not isinstance(schema, dict) or '$ref' not in schema or self.kind(schema) != 'object' or self.nullable(schema)):
                    raise ValueError('Response must reference an object: ' + key)
                if int(status) == 204 and content:
                    raise ValueError('HTTP 204 must not declare response content: ' + key)
                if schema is None and int(status) != 204:
                    raise ValueError('Only HTTP 204 supports an empty success response: ' + key + '/' + status)
                variants[status] = self.schema_key(schema['$ref']) if schema else None
        if not variants or len(set(variants.values())) > 1 and None in variants.values():
            raise ValueError('Unsupported empty/nonempty response combination: ' + key)
        distinct = list(dict.fromkeys(variants.values()))
        result = distinct[0]
        if len(distinct) > 1:
            result = key + 'Result'
            if result in self.schemas:
                raise ValueError('Synthetic response schema conflicts with a component: ' + result)
            fields = {}
            required = None
            for child in distinct:
                schema = self.normalize(self.schemas[child])
                for field, value in schema['properties'].items():
                    if field in fields and self.delphi_type(fields[field]) != self.delphi_type(value):
                        raise ValueError('Conflicting response variant property: ' + key + '.' + field)
                    fields[field] = value
                current = set(schema.get('required', []))
                required = current if required is None else required & current
            self.schemas[result] = {'type': 'object', 'properties': fields, 'required': sorted(required or [])}
        return result, variants

    def params_for(self, key, op):
        body = self.resolve(op.get('requestBody', {}))
        query = [p for p in op['parameters'] if p['in'] == 'query']
        if body and query:
            raise ValueError('Combined body and query requires a compatibility decision: ' + key)
        if body:
            schema_key = self.schema_key(body['content']['application/json']['schema']['$ref'])
            return typename(schema_key, True), schema_key, bool(body.get('required'))
        if query:
            param_key = key + 'Params'
            self.queries[param_key] = {'type': 'object', 'properties': {p['name']: p['schema'] for p in query}, 'required': [p['name'] for p in query if p.get('required')]}
            return typename(param_key), param_key, any(p.get('required') for p in query)
        return None, None, False

    @staticmethod
    def unit_header(unit, uses):
        return MARKER + 'unit ' + unit + ';\n\n{$ZEROBASEDSTRINGS OFF}\n\ninterface\n\nuses\n  ' + ', '.join(uses) + ';\n\n'

    def render_models(self):
        code = self.unit_header('Raims.Models', ['System.SysUtils', 'System.JSON', 'Raims.Core']) + 'type\n'
        model_keys = set(self.schemas) - self.input_schemas
        for result, _ in self.responses.values():
            if result:
                model_keys.add(result)
        def collect_refs(schema):
            if '$ref' in schema:
                key = self.schema_key(schema['$ref'])
                if key not in model_keys:
                    model_keys.add(key)
                    collect_refs(self.schemas[key])
                return
            for child in schema.get('properties', {}).values():
                collect_refs(child)
            for child in schema.get('anyOf', []):
                collect_refs(child)
            if 'items' in schema:
                collect_refs(schema['items'])
        for key in list(model_keys):
            collect_refs(self.schemas[key])
        models = {key: self.schemas[key] for key in model_keys}
        for key in sorted(models):
            self.add_type(typename(key), 'response model ' + key)
            code += '  ' + typename(key) + ' = class;\n'
        code += '\n'
        implementations = []
        for key, raw in sorted(models.items()):
            schema = self.normalize(raw)
            cls = typename(key)
            fields = schema['properties']
            self.check_symbols(fields, key)
            paged = 'page' in fields and 'list' in fields
            base = 'TRaimsCollection' if paged else 'TRaimsResource'
            members = self.member_symbols(COLLECTION_MEMBERS if paged else RESOURCE_MEMBERS, cls)
            if paged:
                for direction in ('Next', 'Previous'):
                    self.add_symbol(members, direction + 'Page', 'page navigation', cls)
            for field in fields:
                self.add_symbol(members, 'Read' + name(field), 'getter for ' + field, cls)
                self.add_symbol(members, identifier(field), 'property ' + field, cls)
            code += '  ' + cls + ' = class(' + base + ')\n  private\n'
            for field, value in fields.items():
                code += '    function Read' + name(field) + ': ' + self.delphi_type(value) + ';\n'
                implementations.append(self.model_getter(cls, field, value))
            code += '  public\n'
            if paged:
                for direction in ('Next', 'Previous'):
                    code += '    function ' + direction + 'Page: ' + cls + '; reintroduce;\n'
                    implementations.append('function ' + cls + '.' + direction + 'Page: ' + cls + ';\nbegin\n  Result := ' + cls + '(inherited ' + direction + 'Page);\nend;\n')
            for field, value in fields.items():
                code += '    property ' + identifier(field) + ': ' + self.delphi_type(value) + ' read Read' + name(field) + ';\n'
            code += '  end;\n\n'
        self.outputs['src/Raims.Models.pas'] = code + 'implementation\n\n' + '\n'.join(implementations) + '\nend.\n'

    def model_getter(self, cls, field, schema):
        typ = self.delphi_type(schema)
        result = 'function ' + cls + '.Read' + name(field) + ': ' + typ + ';\n'
        kind = self.kind(schema)
        key = literal(field)
        getter = {'string': 'GetString', 'integer': 'GetInt64', 'boolean': 'GetBoolean', 'number': 'GetDouble'}
        if kind in getter:
            return result + 'begin\n  Result := ' + getter[kind] + '(' + key + ');\nend;\n'
        if kind == 'object':
            if typ == 'TJSONObject':
                return result + 'begin\n  Result := GetObject(' + key + ');\nend;\n'
            return result + 'var\n  Value: TJSONObject;\nbegin\n  Value := GetObject(' + key + ');\n  if Value = nil then\n    Result := nil\n  else\n    Result := ' + typ + '.Create(Value);\nend;\n'
        if typ == 'TJSONArray':
            return result + 'begin\n  Result := GetArray(' + key + ');\nend;\n'
        item = self.normalize(schema)['items']
        itype = self.delphi_type(item)
        ikind = self.kind(item)
        result += 'var\n  Values: TJSONArray;\n  Index: Integer;\nbegin\n  Result := nil;\n  Values := GetArray(' + key + ');\n  if Values = nil then Exit;\n  SetLength(Result, Values.Count);\n'
        if ikind == 'object':
            result += '  try\n'
            indent = '    '
        else:
            indent = '  '
        result += indent + 'for Index := 0 to Values.Count - 1 do\n  ' + indent + 'begin\n'
        if ikind == 'object':
            result += indent + '  if not (Values.Items[Index] is TJSONObject) then\n' + indent + "    raise EConvertError.Create('Expected a JSON object in " + field + "');\n"
            if itype == 'TJSONObject':
                result += indent + '  Result[Index] := TJSONObject(Values.Items[Index]).Clone as TJSONObject;\n'
            else:
                result += indent + '  Result[Index] := ' + itype + '.Create(TJSONObject(Values.Items[Index]));\n'
        else:
            expected = {'integer': 'TJSONNumber', 'string': 'TJSONString', 'boolean': 'TJSONBool'}[ikind]
            condition = 'RaimsIsJsonString(Values.Items[Index])' if ikind == 'string' else '(Values.Items[Index] is ' + expected + ')'
            result += indent + '  if not ' + condition + ' then\n' + indent + "    raise EConvertError.Create('Unexpected JSON array item type');\n"
            conversion = {'integer': 'StrToInt64(Values.Items[Index].Value)', 'string': 'Values.Items[Index].Value', 'boolean': 'TJSONBool(Values.Items[Index]).AsBoolean'}[ikind]
            result += indent + '  Result[Index] := ' + conversion + ';\n'
        result += indent + 'end;\n'
        if ikind == 'object':
            result += '  except\n    for Index := 0 to Length(Result) - 1 do\n      Result[Index].Free;\n    raise;\n  end;\n'
        return result + 'end;\n'

    def render_params(self):
        code = self.unit_header('Raims.Params', ['System.SysUtils', 'System.JSON', 'Raims.Core']) + 'type\n'
        types = {}
        for key in sorted(self.input_schemas):
            cls = typename(key, True)
            self.add_type(cls, 'input parameters ' + key)
            types[cls] = self.schemas[key]
        for key, schema in sorted(self.queries.items()):
            cls = typename(key)
            self.add_type(cls, 'query parameters ' + key)
            types[cls] = schema
        impl = []
        for cls, raw in sorted(types.items()):
            schema = self.normalize(raw)
            self.check_symbols(schema['properties'], cls)
            members = self.member_symbols(PARAMS_MEMBERS, cls)
            for field, value in schema['properties'].items():
                self.add_symbol(members, 'Set' + name(field), 'setter for ' + field, cls)
                if self.nullable(value):
                    self.add_symbol(members, 'Set' + name(field) + 'Null', 'null setter for ' + field, cls)
                self.add_symbol(members, 'Unset' + name(field), 'omission setter for ' + field, cls)
            code += '  ' + cls + ' = class(TRaimsParams)\n  public\n'
            for field, value in schema['properties'].items():
                typ = self.delphi_type(value, True)
                fn = 'Set' + name(field)
                signature = 'function ' + cls + '.' + fn + '(const Value: ' + typ + '): ' + cls + ';\n'
                code += '    function ' + fn + '(const Value: ' + typ + '): ' + cls + ';\n'
                kind = self.kind(value)
                if kind in {'integer', 'string', 'boolean'}:
                    body = {'integer': 'SetInt64', 'string': 'SetString', 'boolean': 'SetBoolean'}[kind] + '(' + literal(field) + ', Value);'
                    impl.append(signature + 'begin\n  ' + body + '\n  Result := Self;\nend;\n')
                elif kind == 'object' or typ == 'TJSONArray':
                    if typ not in {'TJSONObject', 'TJSONArray'}:
                        raise ValueError('Nested object inputs need explicit ownership support: ' + cls)
                    impl.append(signature + 'begin\n  if Value = nil then\n    raise EArgumentNilException.Create(\'Value\');\n  SetJson(' + literal(field) + ', Value);\n  Result := Self;\nend;\n')
                else:
                    if kind != 'array':
                        raise ValueError('Unsupported input shape: ' + cls + '.' + field)
                    item = self.normalize(value)['items']
                    itype = self.delphi_type(item, True)
                    if self.kind(item) not in {'string', 'integer', 'boolean'}:
                        raise ValueError('Unsupported typed input array item: ' + cls + '.' + field)
                    constructor = {'string': 'TJSONString.Create(Value[Index])', 'integer': 'TJSONNumber.Create(Value[Index])', 'boolean': 'TJSONBool.Create(Value[Index])'}[self.kind(item)]
                    impl.append(signature + 'var\n  Values: TJSONArray;\n  Index: Integer;\nbegin\n  Values := TJSONArray.Create;\n  try\n    for Index := 0 to Length(Value) - 1 do\n      Values.AddElement(' + constructor + ');\n    SetJson(' + literal(field) + ', Values);\n  finally\n    Values.Free;\n  end;\n  Result := Self;\nend;\n')
                if self.nullable(value):
                    nullfn = fn + 'Null'
                    code += '    function ' + nullfn + ': ' + cls + ';\n'
                    impl.append('function ' + cls + '.' + nullfn + ': ' + cls + ';\nbegin\n  SetNull(' + literal(field) + ');\n  Result := Self;\nend;\n')
                unset = 'Unset' + name(field)
                code += '    function ' + unset + ': ' + cls + ';\n'
                impl.append('function ' + cls + '.' + unset + ': ' + cls + ';\nbegin\n  Unset(' + literal(field) + ');\n  Result := Self;\nend;\n')
            code += '  end;\n\n'
        self.outputs['src/Raims.Params.pas'] = code + 'implementation\n\n' + '\n'.join(impl) + '\nend.\n'

    def render_services(self):
        code = self.unit_header('Raims.Services', ['System.SysUtils', 'Raims.Core', 'Raims.Models', 'Raims.Params', 'Raims.Validation']) + 'type\n'
        impl = []
        reference = ['# Method reference\n\nGenerated from the pinned public API contract. Amounts use integer cents; dates use UTC Unix seconds.\n\n', '| Method | HTTP | Parameters | Result | Success statuses | Idempotency key |\n', '| --- | --- | --- | --- | --- | --- |\n']
        metadata = []
        for service, methods in self.services.items():
            cls = 'T' + name(service) + 'Service'
            self.add_type(cls, 'resource service ' + service)
            members = self.member_symbols((OBJECT_MEMBERS - {'Create'}) | {'FRequestor', 'CreateService'}, cls)
            for method in methods:
                self.add_symbol(members, identifier(method), 'resource operation ' + method, cls)
            code += '  ' + cls + ' = class(TRaimsService)\n  public\n    constructor CreateService(const Requestor: IRaimsRequestor);\n'
            impl.append('constructor ' + cls + '.CreateService(const Requestor: IRaimsRequestor);\nbegin\n  inherited Create(Requestor);\nend;\n')
            for method, key in methods.items():
                op = self.operations[key]
                result_key, variants = self.responses[key]
                rt = typename(result_key) if result_key else 'TRaimsResource'
                pt, pk, required = self.params[key]
                paths = [p for p in op['parameters'] if p['in'] == 'path']
                sign = ['const A' + name(p['name']) + ': string' for p in paths]
                args = ['A' + name(p['name']) for p in paths]
                if pt:
                    sign.append('Params: ' + pt)
                    args.append('Params')
                mn = identifier(method)
                extra = ' reintroduce;' if method.lower() == 'create' else ''
                code += '    function ' + mn + '(' + '; '.join(sign) + '): ' + rt + ';' + extra + ' overload;\n' if sign else '    function ' + mn + ': ' + rt + '; overload;\n'
                code += '    function ' + mn + '(' + '; '.join(sign + ['const Options: TRaimsRequestOptions']) + '): ' + rt + '; overload;\n'
                shortsign = '(' + '; '.join(sign) + ')' if sign else ''
